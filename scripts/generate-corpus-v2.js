function toCSV(records) {
  if (!records.length) return '';
  const fields = ['id','title','cipher_family','cipher_type','plaintext','ciphertext','difficulty','language','source_type','license','verified','dataset_version','split'];
  const escape = v => '"' + String(v == null ? '' : v).replace(/\r?\n/g, ' ').replace(/"/g, '""') + '"';
  return [fields.join(','), ...records.map(r => fields.map(f => escape(r[f])).join(','))].join('\n');
}
