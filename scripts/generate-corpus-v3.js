const cleanFn = t => String(t).toUpperCase().replace(/[^A-Z]/g, '');
const idCounters = {};
function nextId(ctype) {
  const k = ctype.replace(/[^a-z0-9]/gi, '-').replace(/-+/g, '-').toLowerCase().replace(/^-|-$/g, '');
  idCounters[k] = (idCounters[k] || 0) + 1;
  return `${k}-v3-${String(idCounters[k]).padStart(4, '0')}`;
}

function testRoundtrip(eng, plain, key) {
  try {
    const ct = eng.encode(plain, key);
    if (!ct || typeof ct !== 'string' || ct === '') return false;
    if (/\?|Key required|not invertible|Need \d|must be at least/i.test(ct)) return false;
    const dt = eng.decode(ct, key);
    const cp = cleanFn(plain);
    const dcp = cleanFn(dt);
    return dcp === cp || dt === plain.toUpperCase() || dt.toUpperCase() === cp || dcp.startsWith(cp);
  } catch { return false; }
}

function makeRecord(engName, plain, keyStr, keyObj, meta) {
  const eng = CE[engName];
  if (!eng || !eng.encode) return null;
  let ct;
  try { ct = eng.encode(plain, keyStr); } catch { return null; }
  if (!ct || typeof ct !== 'string' || ct === '') return null;
  if (/\?|Key required|not invertible|Need \d|must be at least/i.test(ct)) return null;
  const normLen = cleanFn(ct).length;
  const hasSpaces = /[ \n\t]/.test(ct);
  const hasPunct = /[^A-Z0-9 \n\t]/.test(ct);
  const hasLower = /[a-z]/.test(ct);
  return {
    id: nextId(meta.type),
    title: `${meta.type.replace(/_/g, ' ')} — ${meta.diff.charAt(0).toUpperCase() + meta.diff.slice(1)}`,
    cipher_family: meta.family,
    cipher_type: meta.type,
    plaintext: plain.toUpperCase(),
    ciphertext: ct,
    key: keyObj,
    language: meta.lang || 'en',
    alphabet: 'A-Z',
    text_length: ct.length,
    normalized_text_length: normLen,
    spacing: hasSpaces ? 'preserved' : 'removed',
    punctuation: hasPunct ? 'mixed' : 'removed',
    casing: hasLower ? 'mixed' : 'uppercase',
    difficulty: meta.diff,
    source_type: 'synthetic',
    source: 'Generated by Cipher Museum',
    license: 'CC0',
    notes: meta.notes || '',
    expected_attacks: meta.attacks,
    tags: meta.tags,
    created_by: 'Cipher Museum',
    verified: true,
    dataset_version: '2.0',
    split: Math.random() < 0.7 ? 'public' : 'blind',
    transcription_quality: 'clean',
    source_provenance: {
      url: CORPUS_URL,
      archive: 'Cipher Museum Synthetic Corpus v2',
      publication_date: TODAY,
      license: 'CC0'
    }
  };
}

