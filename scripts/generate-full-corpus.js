// ─── Generation Loop ───
const allRecords = [];
let skipped = 0;

for (const cfg of CONFIGS) {
  const eng = CE[cfg.engName];
  if (!eng) { console.warn(`Engine not found: ${cfg.engName}`); continue; }
  const pts = cfg.plaintexts || ALL_PLAINTEXTS;
  for (const [keyStr, keyObj] of cfg.variants) {
    for (const plain of pts) {
      if (!testRoundtrip(eng, plain, keyStr)) { skipped++; continue; }
      const rec = makeRecord(cfg.engName, plain, keyStr, keyObj, cfg);
      if (rec) allRecords.push(rec);
    }
  }
}

console.log(`Generated ${allRecords.length} records (${skipped} skipped/failed roundtrip)`);

// ─── Write Output ───
function writeJsonl(filepath, records) {
  fs.writeFileSync(filepath, records.map(r => JSON.stringify(r)).join('\n') + '\n');
}

const byDiff = { beginner: [], intermediate: [], advanced: [], expert: [] };
for (const r of allRecords) {
  if (byDiff[r.difficulty]) byDiff[r.difficulty].push(r);
}

writeJsonl(path.join(OUT_DIR, 'all.jsonl'), allRecords);
fs.writeFileSync(path.join(OUT_DIR, 'all.json'), JSON.stringify(allRecords, null, 2));

for (const [diff, recs] of Object.entries(byDiff)) {
  writeJsonl(path.join(OUT_DIR, `${diff}.jsonl`), recs);
  console.log(`  ${diff}: ${recs.length} records`);
}

// Update CSV
function toCSV(records) {
  if (!records.length) return '';
  const fields = ['id','title','cipher_family','cipher_type','plaintext','ciphertext','difficulty','language','source_type','license','verified','dataset_version','split'];
  const escape = v => '"' + String(v == null ? '' : v).replace(/\r?\n/g, ' ').replace(/"/g, '""') + '"';
  return [fields.join(','), ...records.map(r => fields.map(f => escape(r[f])).join(','))].join('\n');
}
fs.writeFileSync(path.join(OUT_DIR, 'all.csv'), toCSV(allRecords));

