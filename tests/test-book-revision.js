'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const page = file => new JSDOM(fs.readFileSync(path.join(root, file), 'utf8')).window.document;
const testimony = page('ciphers/navajo-code-talkers.html');
assert.ok(testimony.querySelector('a[href="https://americanindian.si.edu/nk360/code-talkers/coming-home/"]'));
const enigma = page('ciphers/enigma.html');
const asset = enigma.querySelector('img[src="../images/artifacts/mechanical-enigma-machine.png"]');
assert.match(asset.alt, /Teaching diagram/);
assert.doesNotMatch(asset.closest('figure').textContent, /ArnoldReinhold|MIT Flea/);
console.log('Book revision: testimony link and image description passed.');
