'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const page = file => new JSDOM(fs.readFileSync(path.join(root, file), 'utf8')).window.document;
const stager = page('ciphers/stager.html');
const grid = [...stager.querySelectorAll('#word-route tbody tr')].map(row => [...row.cells].map(cell => cell.textContent.trim()));
const routed = [[2, false], [0, true], [3, false], [1, true]].flatMap(([col, up]) => {
  const words = grid.map(row => row[col]);
  return up ? words.reverse() : words;
});
assert.equal(routed.join(' '), 'SUPPLIES AT ORCHARD MOVE TO DAWN LANTERN THE');
assert.equal(grid.flat().map(word => ({ ORCHARD: 'RIVER', LANTERN: 'BRIDGE' }[word] || word)).join(' '), 'MOVE THE SUPPLIES TO RIVER BRIDGE AT DAWN');
const sent = routed.flatMap((word, i) => i % 2 ? [word, 'SKY'] : [word]).join(' ');
assert.ok(stager.querySelector('#word-route').textContent.includes(sent), 'Visible transmitted message must agree with the route and null rule');
assert.ok(!stager.querySelector('#word-route').textContent.includes('NASH VILL'), 'Whole-word example must not split a place name');
const testimony = page('ciphers/navajo-code-talkers.html');
assert.ok(testimony.querySelector('a[href="https://americanindian.si.edu/nk360/code-talkers/coming-home/"]'));
const enigma = page('ciphers/enigma.html');
const asset = enigma.querySelector('img[src="../images/artifacts/mechanical-enigma-machine.png"]');
assert.match(asset.alt, /Teaching diagram/);
assert.doesNotMatch(asset.closest('figure').textContent, /ArnoldReinhold|MIT Flea/);
console.log('Book revision: word route, nulls, vocabulary, testimony link and image description passed.');
